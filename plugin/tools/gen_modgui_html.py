#!/usr/bin/env python3
"""Generates modgui/icon.html from data/pickup_models.csv so the target-model
dropdown always matches the plugin's model list.

Usage: python3 plugin/tools/gen_modgui_html.py
"""

import csv
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", ".."))
CSV = os.path.join(ROOT, "data", "pickups.csv")
CSV_FALLBACK = os.path.join(ROOT, "data", "pickup_models.csv")
OUT = os.path.join(HERE, "..", "modgui", "icon.html")

FROM_NAMES = ["Humbucker", "Single Coil", "Single Coil (Bright)", "Piezo"]

TEMPLATE = """<!-- generated by plugin/tools/gen_modgui_html.py - do not edit -->
<div class="mod-pedal pw-pedal{{{{{{cns}}}}}}">
    <div mod-role="drag-handle" class="mod-drag-handle"></div>
    <div class="pw-select pw-select-from">
        <select mod-role="input-control-port" mod-port-symbol="pickup_from" mod-widget="select" title="Source pickup type">
{from_options}
        </select>
    </div>
    <div class="pw-select pw-select-to">
        <select mod-role="input-control-port" mod-port-symbol="pickup_to" mod-widget="select" title="Target pickup / model">
{to_options}
        </select>
    </div>
    <div class="pw-knob pw-knob-amount" mod-role="input-control-port" mod-port-symbol="amount" title="Amount"></div>
    <div class="pw-knob pw-knob-gain" mod-role="input-control-port" mod-port-symbol="gain" title="Gain"></div>
    <div class="pw-knob pw-knob-tone" mod-role="input-control-port" mod-port-symbol="tone" title="Tone"></div>
    <div class="pw-knob pw-knob-volume" mod-role="input-control-port" mod-port-symbol="volume" title="Volume"></div>
    <div class="pw-knob pw-knob-brightness" mod-role="input-control-port" mod-port-symbol="brightness" title="Brightness"></div>
    <div class="pw-knob pw-knob-bodymix" mod-role="input-control-port" mod-port-symbol="body_amount" title="Body mix"></div>
    <div class="pw-knob pw-knob-thickness" mod-role="input-control-port" mod-port-symbol="body_thickness" title="Body thickness"></div>
    <div class="pw-light" mod-role="bypass-light"></div>
    <div class="pw-footswitch" mod-role="bypass"></div>
    <div class="mod-pedal-input">
        <div class="mod-input" title="Audio Input 1" mod-role="input-audio-port" mod-port-symbol="lv2_audio_in_1"></div>
        <div class="mod-input" title="Audio Input 2" mod-role="input-audio-port" mod-port-symbol="lv2_audio_in_2"></div>
    </div>
    <div class="mod-pedal-output">
        <div class="mod-output" title="Audio Output 1" mod-role="output-audio-port" mod-port-symbol="lv2_audio_out_1"></div>
        <div class="mod-output" title="Audio Output 2" mod-role="output-audio-port" mod-port-symbol="lv2_audio_out_2"></div>
    </div>
</div>
"""


def main():
    path = CSV if os.path.exists(CSV) else CSV_FALLBACK
    with open(path, newline="") as f:
        rows = list(csv.reader(f))
    names = [r[1] for r in rows[1:] if len(r) > 1]
    names += ["E-Custom", "AC-Custom"]
    if len(names) != 29:
        raise SystemExit("expected 29 model names, got %d" % len(names))

    from_opts = "\n".join(
        '            <option value="%d">%s</option>' % (i, n) for i, n in enumerate(FROM_NAMES)
    )
    to_opts = "\n".join(
        '            <option value="%d">%s</option>' % (i, n) for i, n in enumerate(names)
    )
    html = TEMPLATE.format(from_options=from_opts, to_options=to_opts)
    with open(OUT, "w") as f:
        f.write(html)
    print("wrote", OUT)


if __name__ == "__main__":
    main()
