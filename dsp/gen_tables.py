#!/usr/bin/env python3
"""Generate PickupWeaverTables.h from ../data/pickup_models.csv and ../data/navigator.json.

Doubles are written with repr() (shortest round-trip form), so the C++ compiler parses them
back to bit-identical values (this matters for the AC navigator constant 0.44118899999999994).
"""
import csv
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(HERE, "..", "data")


def d(x):
    s = repr(float(x))
    return s if any(c in s for c in ".eEn") else s + ".0"


def arr1(vals, per_line=6):
    out = []
    for i in range(0, len(vals), per_line):
        out.append("        " + ", ".join(d(v) for v in vals[i:i + per_line]) + ",")
    return "\n".join(out)


rows = list(csv.reader(open(os.path.join(DATA, "pickup_models.csv"))))[1:]
presets = [[float(x) for x in r[2:24]] for r in rows if len(r) >= 24]
names = [r[1] for r in rows if len(r) >= 24]
assert len(presets) == 27
nav = json.load(open(os.path.join(DATA, "navigator.json")))

L = []
L.append("// Generated by gen_tables.py -- do not edit.")
L.append("// Sources: data/pickup_models.csv (27 built-in pickup models, 22-param EQ rows) and")
L.append("// data/navigator.json (E-Custom / AC-Custom navigator).")
L.append("#pragma once")
L.append("")
L.append("namespace pw::tables {")
L.append("")
L.append("inline constexpr int kNumPresets = 27;")
L.append("inline constexpr const char* kPresetNames[29] = {")
L.append("    " + ", ".join('"%s"' % n for n in names) + ', "E-Custom", "AC-Custom"')
L.append("};")
L.append("")
L.append("// Row = inner EQ params p0..p21: p1/p2 HP freq/order, p3/p4 low shelf, (p5,p6,p7) (p8,p9,p10)")
L.append("// (p11,p12,p13) peaks freq/bandwidth/gain, p14/p15 high shelf, p16/p17 LP freq/order, p18 out dB.")
L.append("inline constexpr double kPresets[27][22] = {")
for r in presets:
    L.append("    { " + ", ".join(d(v) for v in r) + " },")
L.append("};")
L.append("")
for key, nm in (("E", "E"), ("AC", "AC")):
    t = nav[key]
    L.append("// ---- %s-Custom navigator ----" % nm)
    L.append("inline constexpr int kNav%sNumRows = %d;" % (nm, len(t["rows"])))
    L.append("inline constexpr double kNav%sRows[%d][21] = {" % (nm, len(t["rows"])))
    for r in t["rows"]:
        L.append("    { " + ", ".join(d(v) for v in r) + " },")
    L.append("};")
    L.append("inline constexpr int kNav%sNumTris = %d;" % (nm, len(t["tris"])))
    L.append("inline constexpr int kNav%sTris[%d][3] = {" % (nm, len(t["tris"])))
    L.append("    " + ", ".join("{ %d, %d, %d }" % tuple(x) for x in t["tris"]))
    L.append("};")
    L.append("// decode matrix as dumped: n[j] = sum_i data[j*21 + i] * R[i]")
    L.append("inline constexpr double kNav%sMatrix[441] = {" % nm)
    L.append(arr1(t["matrix_colmajor_21x21"]))
    L.append("};")
    L.append("inline constexpr double kNav%sDefaultRow[19] = {" % nm)
    L.append(arr1(t["default_row19"]))
    L.append("};")
    L.append("inline constexpr double kNav%sU0 = %s, kNav%sUScale = %s;   // u = Y%% * 0.01 * UScale + U0"
             % (nm, d(t["u_from_Y"][0]), nm, d(t["u_from_Y"][1])))
    L.append("inline constexpr double kNav%sV0 = %s, kNav%sVScale = %s;   // v = X%% * 0.01 * VScale + V0"
             % (nm, d(t["v_from_X"][0]), nm, d(t["v_from_X"][1])))
    L.append("")
L.append("} // namespace pw::tables")
open(os.path.join(HERE, "PickupWeaverTables.h"), "w").write("\n".join(L) + "\n")
print("wrote PickupWeaverTables.h")
